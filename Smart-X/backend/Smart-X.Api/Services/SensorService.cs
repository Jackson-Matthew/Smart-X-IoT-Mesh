using Smart_X.Api.Models;
using Smart_X.Api.DTOs;

namespace Smart_X.Api.Services
{

    // Stores and manages registered sensors.
    // Data structure: a generic List;.
    // Why a List,  grows automatically as devices are registered, keeps them
    // in order for the dashboard, and is type-safe ,can only
    // hold Sensor objects.
    public class SensorService
    {
        // In-memory "database" of sensors. Shared because the service is a singleton.
        private readonly List<Sensor> _sensors = [];

        // Turns the incoming request into a full Sensor record and stores it.
        public Sensor RegisterSensor(SensorRegistrationRequest request)
        {
            var sensor = new Sensor
            {
                Id = Guid.NewGuid(),                  // unique ID generated by the gateway
                DeviceIdentifier = request.DeviceIdentifier,
                MacAddress = request.MacAddress,
                DeploymentLocation = request.DeploymentLocation,
                Category = request.Category,
                IsOnline = false,                     // offline until it sends telemetry
                RegisteredAt = DateTime.UtcNow
            };

            _sensors.Add(sensor);
            return sensor;
        }

        // Returns a copy so callers cannot change the internal list directly.
        public List<Sensor> GetAllSensors()
        {
            return _sensors.ToList();
        }

        public Sensor? GetSensorById(Guid id)
        {
            return _sensors.FirstOrDefault(sensor => sensor.Id == id);
        }

        // Used during ingestion: devices identify themselves by name (e.g. "TEMP-001").
        // The comparison ignores upper/lower case.
        public Sensor? GetSensorByDeviceIdentifier(
            string deviceIdentifier)
        {
            return _sensors.FirstOrDefault(sensor =>
                string.Equals(
                    sensor.DeviceIdentifier,
                    deviceIdentifier,
                    StringComparison.OrdinalIgnoreCase));
        }

        // Copies new values onto the stored sensor (e.g. IsOnline, LastSeen).
        public void UpdateSensor(Sensor sensor)
        {
            ArgumentNullException.ThrowIfNull(sensor);

            var existingSensor = _sensors.FirstOrDefault(
                existing => existing.Id == sensor.Id);

            if (existingSensor == null)
            {
                throw new InvalidOperationException(
                    "Sensor does not exist.");
            }

            existingSensor.DeviceIdentifier =
                sensor.DeviceIdentifier;

            existingSensor.MacAddress =
                sensor.MacAddress;

            existingSensor.DeploymentLocation =
                sensor.DeploymentLocation;

            existingSensor.Category =
                sensor.Category;

            existingSensor.IsOnline =
                sensor.IsOnline;

            existingSensor.RegisteredAt =
                sensor.RegisteredAt;

            existingSensor.LastSeen =
                sensor.LastSeen;
        }
    }
}
